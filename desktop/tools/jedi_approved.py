"""Hand-authored pixel art study. No API, ROM, runtime or save-file access.

Every coordinate is drawn directly onto the native 80x80 indexed canvas.
Preview enlargement is nearest-neighbour only. No rejected sprites are reused.
"""
from pathlib import Path
