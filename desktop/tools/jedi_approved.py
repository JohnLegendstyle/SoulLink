class Sprite:
    def __init__(self, palette):
        self.im = Image.new('P', (80, 80), 0)
        colors = [(0, 0, 0)] + [tuple(bytes.fromhex(c)) for c in palette]
        self.im.putpalette([v for c in colors for v in c] + [0] * (768 - len(colors) * 3))
        self.im.info['transparency'] = 0
        self.d = ImageDraw.Draw(self.im)

    def p(self, color, *xy):
        self.d.polygon(list(zip(xy[::2], xy[1::2])), fill=color)

    def r(self, color, *box):
        self.d.rectangle(box, fill=color)

    def l(self, color, *xy, width=1):
        self.d.line(list(zip(xy[::2], xy[1::2])), fill=color, width=width)

    def rgba(self):
        return self.im.convert('RGBA')


